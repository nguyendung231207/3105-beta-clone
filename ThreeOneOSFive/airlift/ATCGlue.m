+ (nullable NSDictionary *)applicationWithBundleID:(NSString *)bundleID
                                          deviceIP:(NSString *)deviceIP
                                       pairingPath:(NSString *)pairingPath
                                             error:(NSError * _Nullable *)error {
    if (!bundleID || bundleID.length == 0) {
        if (error) *error = [NSError errorWithDomain:@"ATCGlue" code:-1 userInfo:@{NSLocalizedDescriptionKey: @"Bundle ID trống"}];
        return nil;
    }
    
    // 1. Check user custom container path override first
    NSString *custom = [[NSUserDefaults standardUserDefaults] stringForKey:@"proxydeck.custom_container_path"];
    if (custom && custom.length > 0) {
        return @{
            @"CFBundleIdentifier": bundleID,
            @"Path": @"",
            @"Container": custom
        };
    }
    
    // 2. Check cache first for instant response
    NSString *cacheKey = [NSString stringWithFormat:@"proxydeck.cached_container.%@", bundleID];
    NSString *cached = [[NSUserDefaults standardUserDefaults] stringForKey:cacheKey];
    if (cached && cached.length > 0) {
        return @{
            @"CFBundleIdentifier": bundleID,
            @"Path": @"",
            @"Container": cached
        };
    }
    
    // 3. For placeholder/generic/mod bundles (e.g. com.app.vip, com.app.test, etc.), check last working container
    BOOL isGenericOrPlaceholder = [bundleID containsString:@"vip"] ||
                                  [bundleID containsString:@"test"] ||
                                  [bundleID containsString:@"mod"] ||
                                  [bundleID containsString:@"proxydeck"] ||
                                  (![bundleID containsString:@"freefire"] && ![bundleID containsString:@"apple"]);
    
    if (isGenericOrPlaceholder) {
        NSString *lastWorking = [[NSUserDefaults standardUserDefaults] stringForKey:@"proxydeck.last_working_container"];
        if (lastWorking && lastWorking.length > 0) {
            [[NSUserDefaults standardUserDefaults] setObject:lastWorking forKey:cacheKey];
            return @{
                @"CFBundleIdentifier": bundleID,
                @"Path": @"",
                @"Container": lastWorking
            };
        }
    }
    
    NSString *pairingFile = GetEffectivePairingPath(pairingPath);
    if (!pairingFile) {
        if (error) *error = [NSError errorWithDomain:@"ATCGlue" code:-404 userInfo:@{NSLocalizedDescriptionKey: @"Không tìm thấy file ghép đôi (airlift_pairing.plist). Vui lòng hoàn tất ghép đôi thiết bị trước."}];
        return nil;
    }
    
    ConfigureTargetHosts(deviceIP);
    
    // Build list of bundle IDs to probe:
    NSMutableArray<NSString *> *candidatesToProbe = [NSMutableArray array];
    if (isGenericOrPlaceholder) {
        [candidatesToProbe addObject:@"com.dts.freefiremax"];
        [candidatesToProbe addObject:@"com.dts.freefireth"];
    } else {
        [candidatesToProbe addObject:bundleID];
        if ([bundleID isEqualToString:@"com.dts.freefiremax"]) {
            [candidatesToProbe addObject:@"com.dts.freefireth"];
        } else if ([bundleID isEqualToString:@"com.dts.freefireth"]) {
            [candidatesToProbe addObject:@"com.dts.freefiremax"];
        }
    }
    
    char *out_container = NULL;
    char *out_error = NULL;
    
    for (NSString *targetBundle in candidatesToProbe) {
        NSLog(@"[ATCGlue] al_find_app_container probing target '%@' via %@...", targetBundle, deviceIP);
        int32_t rc = al_find_app_container(
            [pairingFile UTF8String],
            [targetBundle UTF8String],
            AirliftLogCallback,
            NULL,
            &out_container,
            &out_error
        );
        NSLog(@"[ATCGlue] al_find_app_container probe for '%@' finished: rc=%d, container=%s, error=%s", targetBundle, rc, out_container ? out_container : "none", out_error ? out_error : "none");
        
        if (rc == 0 && out_container != NULL) {
            NSString *containerStr = [NSString stringWithUTF8String:out_container];
            al_string_free(out_container);
            if (out_error) al_string_free(out_error);
            
            // Cache found container path globally and for both games
            [[NSUserDefaults standardUserDefaults] setObject:containerStr forKey:cacheKey];
            [[NSUserDefaults standardUserDefaults] setObject:containerStr forKey:@"proxydeck.last_working_container"];
            [[NSUserDefaults standardUserDefaults] setObject:containerStr forKey:[NSString stringWithFormat:@"proxydeck.cached_container.%@", targetBundle]];
            [[NSUserDefaults standardUserDefaults] setObject:containerStr forKey:@"proxydeck.cached_container.com.app.vip"];
            [[NSUserDefaults standardUserDefaults] setObject:containerStr forKey:@"proxydeck.cached_container.com.app.test"];
            [[NSUserDefaults standardUserDefaults] setObject:containerStr forKey:@"proxydeck.cached_container.com.dts.freefiremax"];
            [[NSUserDefaults standardUserDefaults] setObject:containerStr forKey:@"proxydeck.cached_container.com.dts.freefireth"];
            
            return @{
                @"CFBundleIdentifier": bundleID,
                @"Path": @"",
                @"Container": containerStr
            };
        }
        if (out_error) { al_string_free(out_error); out_error = NULL; }
        if (out_container) { al_string_free(out_container); out_container = NULL; }
    }
    
    // If probing failed, fallback to last working container if recorded
    NSString *fallback = [[NSUserDefaults standardUserDefaults] stringForKey:@"proxydeck.last_working_container"];
    if (fallback && fallback.length > 0) {
        [[NSUserDefaults standardUserDefaults] setObject:fallback forKey:cacheKey];
        return @{
            @"CFBundleIdentifier": bundleID,
            @"Path": @"",
            @"Container": fallback
        };
    }
    
    NSString *errDesc = [NSString stringWithFormat:@"Không tìm thấy container của ứng dụng (%@) qua AirLift. Hãy đảm bảo bạn đã mở game ít nhất 1 lần và VPN 10.7.0.1 đang bật.", bundleID];
    if (error) {
        *error = [NSError errorWithDomain:@"ATCGlue" code:-1 userInfo:@{NSLocalizedDescriptionKey: errDesc}];
    }
    return nil;
}

