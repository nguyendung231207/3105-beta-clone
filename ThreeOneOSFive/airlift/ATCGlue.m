#pragma mark - Rust Core Log Callback

static void AirliftLogCallback(void *ctx, const char *msg) {
    if (!msg) return;
    NSString *line = [NSString stringWithUTF8String:msg];
    if (line) {
        NSLog(@"[AirLift-Core] %@", line);
    } else {
        printf("[AirLift-Core] %s\n", msg);
    }
}

#pragma mark - Grappa Authentication Helper (AirCard-iOS Authentic Tokens)

static NSData *ALDataFromHex(const char *hex) {
    if (!hex) return nil;
    size_t len = strlen(hex);
    if (len % 2 != 0) return nil;
    size_t bytesLen = len / 2;
    NSMutableData *data = [NSMutableData dataWithLength:bytesLen];
    uint8_t *bytes = [data mutableBytes];
    for (size_t i = 0; i < bytesLen; i++) {
        unsigned int byteVal = 0;
        if (sscanf(hex + (i * 2), "%02x", &byteVal) != 1) return nil;
        bytes[i] = (uint8_t)byteVal;
    }
    return data;
}

