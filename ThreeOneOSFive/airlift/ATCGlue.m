#pragma mark - Helper Functions

static NSString *GetEffectivePairingPath(NSString *inputPath) {
    if (inputPath && inputPath.length > 0 && [[NSFileManager defaultManager] fileExistsAtPath:inputPath]) {
        return inputPath;
    }
    NSString *custom = [[NSUserDefaults standardUserDefaults] stringForKey:@"proxydeck.airlift.customPairingPath"];
    if (custom && custom.length > 0 && [[NSFileManager defaultManager] fileExistsAtPath:custom]) {
        return custom;
    }
    NSArray *paths = NSSearchPathForDirectoriesInDomains(NSDocumentDirectory, NSUserDomainMask, YES);
    NSString *docs = paths.firstObject;
    NSString *canonical = [docs stringByAppendingPathComponent:@"airlift_pairing.plist"];
    if ([[NSFileManager defaultManager] fileExistsAtPath:canonical]) {
        return canonical;
    }
    return nil;
}

static void ConfigureTargetHosts(NSString *preferredIP) {
    NSString *deviceIP = @"10.7.0.1";
    if (preferredIP && preferredIP.length > 0 && ![preferredIP isEqualToString:@"10.7.1.1"]) {
        deviceIP = preferredIP;
    }
    const char *targetHost = [deviceIP UTF8String];
    al_set_target_host(targetHost);
    const char *hostsArray[] = { targetHost };
    al_set_target_hosts(hostsArray, 1);
}

