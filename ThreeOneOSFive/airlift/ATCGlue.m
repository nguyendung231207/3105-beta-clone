    NSMutableDictionary *dict = [NSMutableDictionary dictionary];
    for (NSString *p in absolutePaths) {
        NSData *d = [NSData dataWithContentsOfFile:p];
        if (d) {
            dict[p] = d;
        } else if (!allowMissing) {
            if (error) {
                *error = [NSError errorWithDomain:@"ATCGlue" code:-404 userInfo:@{NSLocalizedDescriptionKey: [NSString stringWithFormat:@"Missing %@", p]}];
            }
            return nil;
        }
    }
    return dict;
}

