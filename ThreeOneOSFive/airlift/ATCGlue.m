    (void)tokenFn;
    NSLog(@"[ATCGlue] +load initialized, ALGetGrappaToken retained at %p", tokenFn);
}

+ (void)setupAirLiftLogging {
    static dispatch_once_t onceToken;
    dispatch_once(&onceToken, ^{
        int32_t rc = al_log_init(AirliftLogCallback, NULL);
        NSLog(@"[ATCGlue] Rust AirLift log stream initialized (rc=%d)", rc);
    });
}

