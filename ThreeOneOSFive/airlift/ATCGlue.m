+ (BOOL)writeFilesArbitraryWithDeviceIP:(NSString *)deviceIP
                             pairingPath:(NSString *)pairingPath
                       targetDirectories:(NSArray<NSString *> *)targetDirectories
                               fileNames:(NSArray<NSString *> *)fileNames
                                    data:(NSArray<NSData *> *)data
                                   error:(NSError * _Nullable *)error {
    if (targetDirectories.count == 0 || fileNames.count == 0 || data.count == 0) {
        return YES;
    }
    
    NSLog(@"[ATCGlue] writeFilesArbitrary: %lu files, deviceIP=%@", (unsigned long)fileNames.count, deviceIP);
    
    // First attempt direct POSIX file write (works on iOS < 26 with bad_query lease)
    BOOL allDirectSucceeded = YES;
    for (NSUInteger i = 0; i < fileNames.count; i++) {
        if (i < targetDirectories.count && i < data.count) {
            NSString *dir = targetDirectories[i];
            NSString *fn = fileNames[i];
            NSData *d = data[i];
            NSString *fullPath = [dir stringByAppendingPathComponent:fn];
            [[NSFileManager defaultManager] createDirectoryAtPath:dir withIntermediateDirectories:YES attributes:nil error:nil];
            if (![d writeToFile:fullPath options:NSDataWritingAtomic error:nil]) {
                allDirectSucceeded = NO;
                break;
            }
        }
    }
    if (allDirectSucceeded) {
        NSLog(@"[ATCGlue] Direct POSIX write succeeded for all files.");
        return YES;
    }
    
    // Direct write blocked (iOS 27 sandbox) -> Use Airlift AirTraffic write!
    NSString *pairingFile = GetEffectivePairingPath(pairingPath);
    if (!pairingFile) {
        NSLog(@"[ATCGlue] Error: Missing effective pairing file!");
        if (error) *error = [NSError errorWithDomain:@"ATCGlue" code:-404 userInfo:@{NSLocalizedDescriptionKey: @"Không tìm thấy file ghép đôi (airlift_pairing.plist) để thực hiện ghi tệp ngoài sandbox"}];
        return NO;
    }
    
    ConfigureTargetHosts(deviceIP);
    NSLog(@"[ATCGlue] Target host configured: %@. Pairing file: %@", deviceIP, pairingFile);
    
    // Group files by target directory
    NSMutableDictionary<NSString *, NSMutableArray<NSNumber *> *> *grouped = [NSMutableDictionary dictionary];
    for (NSUInteger i = 0; i < fileNames.count; i++) {
        if (i < targetDirectories.count && i < data.count) {
            NSString *dir = targetDirectories[i];
            if (!grouped[dir]) {
                grouped[dir] = [NSMutableArray array];
            }
            [grouped[dir] addObject:@(i)];
        }
    }
    
    for (NSString *targetDir in grouped) {
        NSArray<NSNumber *> *indices = grouped[targetDir];
        
        NSString *tempDir = [NSTemporaryDirectory() stringByAppendingPathComponent:[NSString stringWithFormat:@"al_write_%@", [[NSUUID UUID] UUIDString]]];
        [[NSFileManager defaultManager] createDirectoryAtPath:tempDir withIntermediateDirectories:YES attributes:nil error:nil];
        
        for (NSNumber *idxNum in indices) {
            NSUInteger idx = [idxNum unsignedIntegerValue];
            NSString *fn = fileNames[idx];
            NSData *d = data[idx];
            NSString *stagedFile = [tempDir stringByAppendingPathComponent:fn];
            [d writeToFile:stagedFile atomically:YES];
        }
        
        NSLog(@"[ATCGlue] Calling al_exploit_write_dir to target: %@ (%lu files staged at %@)...", targetDir, (unsigned long)indices.count, tempDir);
        char *out_error = NULL;
        int32_t rc = al_exploit_write_dir(
            [pairingFile UTF8String],
            [tempDir UTF8String],
            [targetDir UTF8String],
            AirliftLogCallback,
            NULL,
            &out_error
        );
        NSLog(@"[ATCGlue] al_exploit_write_dir completed with rc=%d, error=%s", rc, out_error ? out_error : "none");
        
        [[NSFileManager defaultManager] removeItemAtPath:tempDir error:nil];
        
        if (rc != 0) {
            NSString *rawErr = out_error ? [NSString stringWithUTF8String:out_error] : @"";
            NSString *errDesc = rawErr;
            if ([rawErr containsString:@"ReadyForSync not observed"] || [rawErr containsString:@"Apple Books"]) {
                errDesc = @"Đồng bộ AirTraffic thất bại: Thiết bị không phản hồi 'ReadyForSync'. Vui lòng kiểm tra ứng dụng 'Apple Books' (Sách) đã được cài đặt trên iPhone để iOS cho phép đồng bộ file.";
            } else if (errDesc.length == 0) {
                errDesc = @"Ghi tệp qua AirLift/AirTraffic thất bại. Vui lòng kiểm tra VPN LocalDevVPN 10.7.0.1 đã bật chưa.";
            }
            if (out_error) al_string_free(out_error);
            if (error) {
                *error = [NSError errorWithDomain:@"ATCGlue" code:rc userInfo:@{NSLocalizedDescriptionKey: errDesc}];
            }
            return NO;
        }
        if (out_error) al_string_free(out_error);
    }
    
    return YES;
}

