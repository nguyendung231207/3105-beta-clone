+ (BOOL)verifyPairingRecordWithDeviceIP:(NSString *)deviceIP
                            pairingPath:(NSString *)pairingPath
                                  error:(NSError * _Nullable *)error {
    NSString *pairingFile = GetEffectivePairingPath(pairingPath);
    if (!pairingFile || ![[NSFileManager defaultManager] fileExistsAtPath:pairingFile]) {
        if (error) {
            *error = [NSError errorWithDomain:@"ATCGlue"
                                         code:-404
                                     userInfo:@{NSLocalizedDescriptionKey: @"Không tìm thấy file ghép đôi (airlift_pairing.plist). Vui lòng hoàn tất ghép đôi thiết bị trước."}];
        }
        return NO;
    }
    
    ConfigureTargetHosts(deviceIP);
    NSLog(@"[ATCGlue] verifyPairingRecord: probing deviceIP=%@ with pairingFile=%@", deviceIP, pairingFile);
    
    char *out_container = NULL;
    char *out_error = NULL;
    
    // Live probe against RSD / lockdown by querying mobile safari container
    int32_t rc = al_find_app_container(
        [pairingFile UTF8String],
        "com.apple.mobilesafari",
        AirliftLogCallback,
        NULL,
        &out_container,
        &out_error
    );
    
    NSLog(@"[ATCGlue] verify probe completed: rc=%d, error=%s", rc, out_error ? out_error : "none");
    
    if (rc == 0) {
        if (out_container) al_string_free(out_container);
        if (out_error) al_string_free(out_error);
        return YES;
    }
    
    NSString *rawErr = out_error ? [NSString stringWithUTF8String:out_error] : @"Không thể kết nối hoặc xác thực với thiết bị qua LocalDevVPN.";
    if (out_container) al_string_free(out_container);
    if (out_error) al_string_free(out_error);
    
    NSString *lowerErr = [rawErr lowercaseString];
    NSString *userMessage = rawErr;
    if ([lowerErr containsString:@"pair"] || [lowerErr containsString:@"ssl"] || [lowerErr containsString:@"handshake"] || [lowerErr containsString:@"trust"] || [lowerErr containsString:@"invalid"] || [lowerErr containsString:@"denied"]) {
        userMessage = [NSString stringWithFormat:@"Thiết bị đã từ chối xác thực (ghép đôi đã bị hủy trên iPhone): %@", rawErr];
    }
    
    if (error) {
        *error = [NSError errorWithDomain:@"ATCGlue" code:rc userInfo:@{NSLocalizedDescriptionKey: userMessage}];
    }
    return NO;
}

